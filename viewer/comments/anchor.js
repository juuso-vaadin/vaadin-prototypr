/**
 * Comment anchors (SPEC.md §6.4): turning a click in the prototype into a stable
 * reference, and finding that reference again later.
 *
 * anchor = {
 *   protoId?  nearest [data-proto-id] around the click (preferred)
 *   id?       else the nearest element id that looks hand-written
 *   path?     else a path from the document through shadow roots:
 *             [[ 'body:1', 'div:0', ... ], [ ...inside the next shadow root ], ...]
 *             each step is "<tag>:<index among element children>"
 *   offset    { x, y } click position as a fraction of the anchor element's box
 *   fallback  { xPct, yPx } click position relative to the page (kept for reference)
 *   label     short human description, e.g. 'orders-grid' or 'vaadin-button "Save"'
 * }
 */

// The prototype runs in an iframe, i.e. another JavaScript realm: `instanceof
// ShadowRoot` / `instanceof Element` against the viewer's classes would be false.
// These checks work across realms.
const isShadowRoot = (n) => n?.nodeType === 11 && !!n.host;
const isElement = (n) => n?.nodeType === 1;

/** The composed-tree parent: crosses from a shadow root to its host. */
function parentOf(el) {
  if (el.parentElement) return el.parentElement;
  const root = el.getRootNode();
  return isShadowRoot(root) ? root.host : null;
}

// Ids generated by components (input-vaadin-text-field-12, ...) change between loads.
const looksGenerated = (id) => /\d+$/.test(id) || /^(vaadin|input|label|error-message|helper-text)-/.test(id);

export function anchorFromEvent(event) {
  let target = event.composedPath()[0];
  if (!isElement(target)) target = target?.parentElement ?? target?.parentNode?.host;
  if (!target) return null;
  const doc = target.ownerDocument;
  const win = doc.defaultView;

  let protoEl = null;
  let idEl = null;
  for (let el = target; el; el = parentOf(el)) {
    if (el.hasAttribute?.('data-proto-id')) { protoEl = el; break; }
    if (!idEl && el.id && !looksGenerated(el.id) && el.getRootNode() === doc) idEl = el;
  }
  const el = protoEl ?? idEl ?? target;
  const r = el.getBoundingClientRect();
  const clamp = (v) => Math.min(1, Math.max(0, v));
  const anchor = {
    offset: {
      x: r.width ? Number(clamp((event.clientX - r.left) / r.width).toFixed(4)) : 0.5,
      y: r.height ? Number(clamp((event.clientY - r.top) / r.height).toFixed(4)) : 0.5,
    },
    fallback: {
      xPct: Number((event.clientX / win.innerWidth).toFixed(4)),
      yPx: Math.round(event.clientY + win.scrollY),
    },
    label: describe(protoEl, idEl, target),
  };
  if (protoEl) anchor.protoId = protoEl.getAttribute('data-proto-id');
  else if (idEl) anchor.id = idEl.id;
  else anchor.path = pathTo(target);
  return { anchor, element: el };
}

function describe(protoEl, idEl, target) {
  if (protoEl) return protoEl.getAttribute('data-proto-id');
  if (idEl) return `#${idEl.id}`;
  const text = (target.textContent ?? '').trim().replace(/\s+/g, ' ').slice(0, 40);
  return `${target.localName}${text ? ` "${text}"` : ''}`;
}

function pathTo(el) {
  const segments = [];
  let steps = [];
  let node = el;
  while (node) {
    const parent = node.parentElement;
    if (parent) {
      steps.unshift(`${node.localName}:${[...parent.children].indexOf(node)}`);
      node = parent;
      continue;
    }
    const root = node.getRootNode();
    if (isShadowRoot(root)) {
      steps.unshift(`${node.localName}:${[...root.children].indexOf(node)}`);
      segments.unshift(steps);
      steps = [];
      node = root.host;
    } else {
      steps.unshift(`${node.localName}:0`); // <html>
      segments.unshift(steps);
      node = null;
    }
  }
  return segments;
}

function followPath(doc, path) {
  let root = doc;
  let el = null;
  for (let s = 0; s < path.length; s++) {
    if (s > 0) {
      root = el?.shadowRoot;
      if (!root) return null;
    }
    let children = s === 0 ? [doc.documentElement] : [...root.children];
    for (const [i, step] of path[s].entries()) {
      const [tag, idx] = step.split(':');
      el = children[s === 0 && i === 0 ? 0 : Number(idx)];
      if (!el || el.localName !== tag) return null;
      children = [...el.children];
    }
  }
  return el;
}

/** querySelector that also looks into open shadow roots. */
function deepQuery(root, selector) {
  const hit = root.querySelector(selector);
  if (hit) return hit;
  for (const el of root.querySelectorAll('*')) {
    if (el.shadowRoot) {
      const inner = deepQuery(el.shadowRoot, selector);
      if (inner) return inner;
    }
  }
  return null;
}

/**
 * Finds an anchor in a document.
 * → { status: 'visible', x, y }   pin position in the frame's viewport coordinates
 *   { status: 'hidden' }          element exists but isn't rendered (other size, closed dialog)
 *   { status: 'missing' }         element is gone: the thread is outdated
 */
export function resolveAnchor(anchor, doc) {
  if (!doc?.documentElement || !anchor) return { status: 'missing' };
  let el = null;
  try {
    if (anchor.protoId) el = deepQuery(doc, `[data-proto-id="${CSS.escape(anchor.protoId)}"]`);
    else if (anchor.id) el = doc.getElementById(anchor.id);
    else if (anchor.path) el = followPath(doc, anchor.path);
  } catch {
    el = null;
  }
  if (!el) return { status: 'missing' };
  const r = el.getBoundingClientRect();
  const visible = (r.width > 0 || r.height > 0) && (el.checkVisibility ? el.checkVisibility({ visibilityProperty: true }) : true);
  if (!visible) return { status: 'hidden', element: el };
  return {
    status: 'visible',
    element: el,
    x: r.left + (anchor.offset?.x ?? 0.5) * r.width,
    y: r.top + (anchor.offset?.y ?? 0.5) * r.height,
  };
}

/** One line for people (and for the panel): what the comment is attached to. */
export function anchorLabel(anchor) {
  return anchor?.label || anchor?.protoId || (anchor?.id ? `#${anchor.id}` : 'page');
}
